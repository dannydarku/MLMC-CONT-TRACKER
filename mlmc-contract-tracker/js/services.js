/* =========================================================================
   Service layer: file storage (Mock + OneDrive stub)
   and a tiny PDF generator used to make low-storage sample documents.
   Swap the implementations here when moving to production.
   ========================================================================= */
window.MLMC = window.MLMC || {};

(function (M) {
  /* ---------------------------------------------------------------- PDF */
  // Builds a minimal single-page PDF (Helvetica) entirely in the browser.
  // ~2–3 KB per document, so mock files cost almost no storage.
  function pdfEsc(s) {
    return String(s).replace(/[^\x20-\x7E]/g, (c) => (c === '—' || c === '–' ? '-' : c === '→' ? '->' : '')).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
  }
  M.makePdf = function (ops) {
    // ops: [{t:'text', x, y, size, bold, text}, {t:'line', x1,y1,x2,y2,w}, {t:'rect', x,y,w,h,lw}]
    let content = '';
    ops.forEach((o) => {
      if (o.t === 'text') content += `BT /${o.bold ? 'F2' : 'F1'} ${o.size || 11} Tf ${o.x} ${o.y} Td (${pdfEsc(o.text)}) Tj ET\n`;
      if (o.t === 'line') content += `${o.w || 1} w ${o.x1} ${o.y1} m ${o.x2} ${o.y2} l S\n`;
      if (o.t === 'rect') content += `${o.lw || 1} w ${o.x} ${o.y} ${o.w} ${o.h} re S\n`;
    });
    const objs = [
      '<< /Type /Catalog /Pages 2 0 R >>',
      '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
      '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
      `<< /Length ${content.length} >>\nstream\n${content}endstream`,
    ];
    let out = '%PDF-1.4\n';
    const offsets = [];
    objs.forEach((o, i) => { offsets.push(out.length); out += `${i + 1} 0 obj\n${o}\nendobj\n`; });
    const xref = out.length;
    out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n`;
    offsets.forEach((off) => { out += String(off).padStart(10, '0') + ' 00000 n \n'; });
    out += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
    return new Blob([out], { type: 'application/pdf' });
  };

  // Cover page laid out like the MLMC controlled-document template.
  M.coverPdf = function (rec, lookups) {
    const dept = lookups.deptName(rec.dept);
    const type = lookups.typeName(rec.type);
    const ops = [];
    const T = (x, y, text, size, bold) => ops.push({ t: 'text', x, y, text, size, bold });
    ops.push({ t: 'rect', x: 40, y: 700, w: 532, h: 60, lw: 1.5 });
    ops.push({ t: 'line', x1: 210, y1: 700, x2: 210, y2: 760 });
    ops.push({ t: 'line', x1: 210, y1: 745, x2: 572, y2: 745 });
    ops.push({ t: 'line', x1: 210, y1: 715, x2: 572, y2: 715 });
    T(52, 735, 'Makati Life', 15, true); T(52, 718, 'MEDICAL CENTER', 8, false);
    T(216, 750, dept, 8); T(216, 727, rec.title.slice(0, 60), 11, true);
    T(216, 704, type, 8); T(400, 704, 'Effective Date: ' + M.fmt(rec.effectiveDate), 8); T(520, 704, 'Version: ' + rec.version, 8);
    T(80, 640, (rec.category === 'Contract' ? 'CONTRACT' : type.toUpperCase() + 'S'), 16, true);
    ops.push({ t: 'line', x1: 78, y1: 630, x2: 534, y2: 630, w: 2.5 });
    const words = rec.title.toUpperCase().split(' ');
    let line = '', y = 585;
    words.forEach((w) => { if ((line + ' ' + w).length > 22) { T(80, y, line.trim(), 34, true); y -= 40; line = ''; } line += ' ' + w; });
    T(80, y, line.trim(), 34, true);
    ops.push({ t: 'line', x1: 78, y1: y - 22, x2: 534, y2: y - 22, w: 2.5 });
    let yy = y - 55;
    const row = (k, v) => { T(84, yy, k, 11); T(220, yy, v || 'Not Applicable', 11); yy -= 17; };
    row('Document Code:', rec.code);
    row('Effective Date:', M.fmt(rec.effectiveDate));
    row('Last Revised Date:', rec.lastRevisedDate ? M.fmt(rec.lastRevisedDate) : 'Not Applicable');
    row('Version:', rec.version);
    row('Document Owner:', lookups.deptName(rec.ownerDept).toUpperCase());
    if (rec.category === 'Contract') { row('Counterparty:', rec.counterparty); row('Expiry Date:', M.fmt(rec.expiryDate)); }
    yy -= 25;
    const sig = (label, p) => {
      if (!p || !p.name) return;
      T(84, yy, label, 11); yy -= 22; T(84, yy, '[Signed original on file]', 9); yy -= 13;
      T(84, yy, p.name, 11, true); yy -= 12; T(84, yy, p.title || '', 8); yy -= 30;
    };
    sig('Prepared by:', rec.preparedBy); sig('Approved by:', rec.approvedBy);
    T(130, 40, 'SAMPLE / MOCK FILE generated by the MLMC Contract & Document Tracker prototype', 7);
    return M.makePdf(ops);
  };

  /* ------------------------------------------------------------ STORAGE */
  // Common interface every storage provider implements.
  //   getFileInfo(record) -> {name, size, source}
  //   download(record)    -> Promise<Blob>
  //   upload(record, File)-> Promise<{name,size,source}>
  class MockStorage {
    constructor(store) { this.store = store; this.name = 'Mock storage (browser)'; }
    getFileInfo(rec) {
      const f = this.store.state.files[rec.id];
      if (f) return { name: f.name, size: f.size, source: 'Uploaded (mock)' };
      return { name: rec.code + '.pdf', size: null, source: 'Generated sample' };
    }
    async download(rec) {
      const f = this.store.state.files[rec.id];
      if (f) { const res = await fetch(f.dataUrl); return res.blob(); }
      return M.coverPdf(rec, this.store.lookups);
    }
    async upload(rec, file) {
      const MAX = 300 * 1024; // keep the prototype "low storage"
      if (file.size > MAX) throw new Error(`File is ${(file.size / 1024).toFixed(0)} KB. The prototype's mock storage accepts up to 300 KB. Larger files will go to OneDrive once it's connected.`);
      const dataUrl = await new Promise((res, rej) => { const fr = new FileReader(); fr.onload = () => res(fr.result); fr.onerror = rej; fr.readAsDataURL(file); });
      this.store.state.files[rec.id] = { name: file.name, size: file.size, type: file.type, dataUrl };
      return { name: file.name, size: file.size, source: 'Uploaded (mock)' };
    }
  }

  // OneDrive / SharePoint provider — STUB.
  // Production wiring (Microsoft Graph):
  //   1. Register an app in Microsoft Entra ID (Azure AD); delegated scope Files.ReadWrite.All (+ User.Read).
  //   2. Sign users in with MSAL.js (@azure/msal-browser) using tenantId + clientId.
  //   3. Download: GET  https://graph.microsoft.com/v1.0/me/drive/root:{rootFolder}/{code}.pdf:/content
  //      Upload:   PUT  https://graph.microsoft.com/v1.0/me/drive/root:{rootFolder}/{code}.pdf:/content
  //      (for a shared team library use /sites/{site-id}/drive/... instead of /me/drive)
  class OneDriveStorage {
    constructor(config) { this.config = config; this.name = 'OneDrive'; }
    getFileInfo(rec) { return { name: rec.code + '.pdf', size: null, source: 'OneDrive: ' + this.config.rootFolder }; }
    async download() { throw new Error('OneDrive is not connected in this prototype.'); }
    async upload() { throw new Error('OneDrive is not connected in this prototype.'); }
  }

  M.createStorage = function (store) {
    const od = store.state.settings.onedrive;
    return od.connected ? new OneDriveStorage(od) : new MockStorage(store);
  };
})(window.MLMC);
